#!/usr/bin/env node
/**
 * verify.mjs — prove the preset compiles, then measure how faithfully it covers the source site.
 *
 *   node verify.mjs <preset-project-dir> --analysis <extract-out-dir | analysis.json> [--install]
 *
 * 1. codegen + full panda build (catches bad token references, invalid conditions, typos)
 * 2. generates src/showcase.tsx that touches every textStyle / layerStyle / recipe variant,
 *    then checks each one really produced CSS
 * 3. compares what the site renders (analysis.json) with what the preset resolves to (panda --spec),
 *    category by category, and writes FIDELITY.md
 * Exit code 1 if the preset does not compile or a style/recipe fails to emit CSS. Coverage never fails the run:
 * it is a to-do list for the next iteration.
 */
import fs from 'node:fs'
import path from 'node:path'
import { execSync } from 'node:child_process'
import { parseColor, toHex, distance, flatten } from './lib/color.mjs'

const argv = process.argv.slice(2)
const flag = (n, d) => { const i = argv.indexOf(`--${n}`); return i < 0 ? d : argv[i + 1] }
const dir = path.resolve(argv.find((a, i) => !a.startsWith('--') && !(argv[i - 1] || '').startsWith('--')) || '.')
const analysisArg = flag('analysis')
const s2p = path.join(dir, '.s2p')
fs.mkdirSync(s2p, { recursive: true })

const sh = (cmd) => {
  try { return { ok: true, out: execSync(cmd, { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 180000 }) } }
  catch (e) { return { ok: false, out: `${e.stdout || ''}\n${e.stderr || ''}\n${e.message}` } }
}
const strip = (s) => s.replace(/\x1b\[[0-9;]*m/g, '')
const problems = []
const log = (m) => console.log(m)

// ── 0. dependencies ──
const hasDep = (n) => fs.existsSync(path.join(dir, 'node_modules', n))
if (!hasDep('@pandacss/dev') || !hasDep('@pandacss/preset-base')) {
  if (argv.includes('--install')) { log('installing dependencies…'); const r = sh('npm install --no-audit --no-fund'); if (!r.ok) { console.error(strip(r.out)); process.exit(1) } }
  else { console.error('Missing @pandacss/dev or @pandacss/preset-base. Re-run with --install, or: cd <dir> && npm install'); process.exit(1) }
}

// ── 1. codegen + first build (to learn the names) ──
log('▶ panda codegen')
let r = sh('npx panda codegen --no-color')
if (!r.ok || /error/i.test(strip(r.out).split('\n').filter((l) => !/diagnostics: 0/.test(l)).join('\n'))) {
  console.error(strip(r.out)); console.error('✗ codegen failed — fix the preset first.'); process.exit(1)
}
log('▶ panda build (spec)')
r = sh('npx panda --spec=.s2p/spec.json --no-color')
if (!r.ok) { console.error(strip(r.out)); console.error('✗ build failed.'); process.exit(1) }
const buildNotes = strip(r.out).split('\n').filter((l) => /warn|error|unresolved|diagnostic/i.test(l) && !/diagnostics: 0/.test(l))
let spec = JSON.parse(fs.readFileSync(path.join(s2p, 'spec.json'), 'utf8'))

// ── 2. showcase: exercise every composition style and recipe variant ──
const ts = Object.keys(spec.textStyles || {})
const ls = Object.keys(spec.layerStyles || {})
const recipes = spec.recipes || {}
let src = `// AUTO-GENERATED by verify.mjs — touches every textStyle, layerStyle and recipe variant so Panda emits their CSS.\n`
src += `import { css } from '../styled-system/css'\n`
const rnames = Object.keys(recipes)
// Named imports + direct calls: Panda's static extractor only follows calls it can see by name.
if (rnames.length) src += `import { ${rnames.join(', ')} } from '../styled-system/recipes'\n`
src += `export const textStyles = [\n${ts.map((n) => `  css({ textStyle: '${n}' }),`).join('\n')}\n]\n`
src += `export const layerStyles = [\n${ls.map((n) => `  css({ layerStyle: '${n}' }),`).join('\n')}\n]\n`
src += `export const recipes = [\n`
for (const [name, rc] of Object.entries(recipes)) {
  src += `  ${name}({}),\n`
  for (const [vname, v] of Object.entries(rc.variants || {})) for (const val of v.values || []) src += `  ${name}({ ${vname}: ${JSON.stringify(val)} }),\n`
}
src += `]\n`
fs.mkdirSync(path.join(dir, 'src'), { recursive: true })
fs.writeFileSync(path.join(dir, 'src/showcase.tsx'), src)

r = sh('npx panda --spec=.s2p/spec.json --no-color')
if (!r.ok) { console.error(strip(r.out)); process.exit(1) }
spec = JSON.parse(fs.readFileSync(path.join(s2p, 'spec.json'), 'utf8'))
const cssFile = ['styled-system/styles.css', 'styles.css'].map((p) => path.join(dir, p)).find((p) => fs.existsSync(p))
const css = cssFile ? fs.readFileSync(cssFile, 'utf8') : ''
const missingCss = []
for (const n of ts) if (!css.includes(`.textStyle_${n}`)) missingCss.push(`textStyle ${n}`)
for (const n of ls) if (!css.includes(`.layerStyle_${n}`)) missingCss.push(`layerStyle ${n}`)
for (const [n, rc] of Object.entries(recipes)) {
  const cls = rc.className || n
  if (!css.includes(`.${cls}`)) missingCss.push(`recipe ${n}`)
}
if (missingCss.length) problems.push(`No CSS emitted for: ${missingCss.join(', ')}`)

// ── resolved token tables ──
const values = spec.values || []
const byCat = {}
for (const v of values) {
  const cat = v.token.split('.')[0]
  ;(byCat[cat] ||= []).push(v)
}
const cssVarOf = Object.fromEntries(Object.entries(spec.tokens || {}).map(([p, t]) => [t.cssVar, p]))
const baseValue = Object.fromEntries(values.filter((v) => !v.condition).map((v) => [v.token, v.value]))
const resolveVar = (s, depth = 0) => (typeof s === 'string' && depth < 6 ? s.replace(/var\((--[a-z0-9-]+)(?:,[^)]*)?\)/gi, (m, name) => { const p = cssVarOf[name]; return p && baseValue[p] !== undefined ? resolveVar(baseValue[p], depth + 1) : m }) : s)

const sum = (a) => a.reduce((x, y) => x + y, 0)
const pct = (n, d) => (d ? Math.round((n / d) * 100) : 100)

// ── 3. coverage vs the source site ──
let analysis = null
if (analysisArg) {
  const p = path.resolve(analysisArg)
  const f = fs.existsSync(p) && fs.statSync(p).isDirectory() ? path.join(p, 'analysis.json') : p
  if (fs.existsSync(f)) analysis = JSON.parse(fs.readFileSync(f, 'utf8'))
  else console.warn(`analysis not found at ${f} — skipping fidelity comparison`)
}

const md = []
const rootPx = analysis?.meta?.rootFontSize || 16
const toPx = (v) => {
  if (typeof v !== 'string') return null
  const m = String(v).trim().match(/^(-?[\d.]+)(px|rem|em)?$/)
  if (!m) return null
  return m[2] === 'rem' || m[2] === 'em' ? Number(m[1]) * rootPx : Number(m[1])
}
const summary = {}

const prettyHex = (rgba) => toHex(rgba)
if (analysis) {
  // colours
  const tokColors = (byCat.colors || []).map((v) => ({ path: v.token, cond: v.condition || 'base', rgba: parseColor(v.value) })).filter((v) => v.rgba)
  const cmpColors = (observed, conds, label) => {
    const pool = tokColors.filter((t) => conds.includes(t.cond))
    const rows = []
    for (const c of observed.filter((c) => c.weight >= 3).slice(0, 40)) {
      const o = parseColor(c.hex)
      const of = flatten(o)
      let best = null
      for (const t of pool) {
        const d = distance(of, flatten(t.rgba))
        if (!best || d < best.d) best = { d, t }
      }
      const status = !best ? 'missing' : best.d <= 0.5 ? 'exact' : best.d <= 2 ? 'near' : 'missing'
      rows.push({ hex: c.hex, weight: c.weight, status, token: best?.t.path, tokHex: best ? prettyHex(best.t.rgba) : '', d: best ? +best.d.toFixed(2) : null })
    }
    const total = sum(rows.map((r) => r.weight))
    const good = sum(rows.filter((r) => r.status !== 'missing').map((r) => r.weight))
    const exact = sum(rows.filter((r) => r.status === 'exact').map((r) => r.weight))
    summary[label] = `${pct(good, total)}% (exact ${pct(exact, total)}%)`
    md.push(`\n### ${label}\nWeighted coverage **${pct(good, total)}%** — exact ${pct(exact, total)}%. Distance is OKLab×100: ≤0.5 identical, ≤2 near, >2 missing.\n`)
    md.push('| observed | weight | status | nearest token | token value | Δ |\n| --- | --- | --- | --- | --- | --- |')
    for (const r of rows) md.push(`| ${r.hex} | ${r.weight} | ${r.status === 'missing' ? '❌ missing' : r.status === 'near' ? '≈ near' : '✓ exact'} | ${r.token ?? ''} | ${r.tokHex} | ${r.d ?? ''} |`)
  }
  md.push('\n## Colours')
  cmpColors(analysis.colors, ['base'], 'Colours — light')
  if (analysis.darkColors) {
    const darkAware = tokColors.some((t) => t.cond !== 'base')
    if (!darkAware) problems.push('Source has a dark theme but the preset defines no dark semantic-token values.')
    cmpColors(analysis.darkColors, ['base', ...new Set(tokColors.map((t) => t.cond).filter((c) => c !== 'base'))], 'Colours — dark (any dark-condition value or raw token)')
  }

  // type scale
  md.push('\n## Typography')
  const tokSizes = (byCat.fontSizes || []).map((v) => ({ path: v.token, px: toPx(resolveVar(v.value)) })).filter((v) => v.px !== null)
  const sizeRows = analysis.fontSizes.filter((s) => s.chars >= 5).map((s) => {
    const hit = tokSizes.find((t) => Math.abs(t.px - s.px) < 0.51)
    return { px: s.px, chars: s.chars, token: hit?.path }
  })
  const sGood = sum(sizeRows.filter((r) => r.token).map((r) => r.chars)), sTot = sum(sizeRows.map((r) => r.chars))
  summary['Font sizes'] = `${pct(sGood, sTot)}%`
  md.push(`\nFont sizes covered: **${pct(sGood, sTot)}%** (±0.5px).  Missing: ${sizeRows.filter((r) => !r.token).map((r) => `${r.px}px (${r.chars} chars)`).join(', ') || 'none'}`)

  const fams = (byCat.fonts || []).map((v) => String(v.value).toLowerCase())
  const famRows = analysis.fontFamilies.slice(0, 4).map((f) => ({ f: f.family, chars: f.chars, ok: fams.some((x) => x.includes(f.family.toLowerCase())) }))
  summary['Font families'] = `${pct(sum(famRows.filter((r) => r.ok).map((r) => r.chars)), sum(famRows.map((r) => r.chars)))}%`
  md.push(`\nFont families: ${famRows.map((r) => `${r.ok ? '✓' : '❌'} ${r.f}`).join(', ')}`)

  // text styles: parse compiled .textStyle_* blocks and compare to what the site renders
  const tsBlocks = {}
  for (const m of css.matchAll(/\.textStyle_([\w-]+)\s*\{([^}]*)\}/g)) {
    const d = Object.fromEntries(m[2].split(';').map((x) => x.split(/:(.+)/).map((y) => y?.trim())).filter((x) => x[0] && x[1]))
    const size = toPx(resolveVar(d['font-size']))
    let lh = resolveVar(d['line-height'])
    lh = lh === undefined ? null : /px|rem|em/.test(lh) && size ? toPx(lh) / size : parseFloat(lh)
    const fam = (resolveVar(d['font-family']) || '').split(',')[0].replace(/["']/g, '').trim().toLowerCase()
    tsBlocks[m[1]] = { size, weight: String(resolveVar(d['font-weight']) ?? ''), lh, fam }
  }
  const top = analysis.typeStyles.filter((t) => t.chars >= 5).slice(0, 14)
  const tsRows = top.map((t) => {
    const hit = Object.entries(tsBlocks).find(([, b]) => b.size && Math.abs(b.size - t.size) < 0.51 && b.weight === String(t.weight) && (b.lh === null || t.lineHeight === 'normal' || Math.abs(b.lh - t.lineHeight) < 0.06))
    return { t, hit: hit?.[0] }
  })
  const tsGood = sum(tsRows.filter((r) => r.hit).map((r) => r.t.chars)), tsTot = sum(tsRows.map((r) => r.t.chars))
  summary['Text styles'] = `${pct(tsGood, tsTot)}%`
  md.push(`\n### Text styles — ${pct(tsGood, tsTot)}% of rendered text matches a textStyle (size ±0.5px, same weight, line-height ±0.06)\n`)
  md.push('| site renders | textStyle | tags / sample |\n| --- | --- | --- |')
  for (const { t, hit } of tsRows) md.push(`| ${t.family} ${t.size}px / ${t.weight} / lh ${t.lineHeight}${t.letterSpacingEm ? ` / ${t.letterSpacingEm}em` : ''} | ${hit ? '✓ ' + hit : '❌ none'} | ${t.tags} · ${t.sample.slice(0, 30)} |`)

  // spacing
  md.push('\n## Spacing, shape, depth, motion')
  const tokSpace = [...(byCat.spacing || []), ...(byCat.sizes || [])].map((v) => toPx(resolveVar(v.value))).filter((v) => v !== null && v >= 0)
  const spRows = analysis.spacingTop.map((s) => ({ ...s, ok: tokSpace.some((t) => Math.abs(t - s.px) < 0.51) }))
  summary['Spacing'] = `${pct(sum(spRows.filter((r) => r.ok).map((r) => r.count)), sum(spRows.map((r) => r.count)))}%`
  md.push(`\nSpacing values used (top 18) covered: **${summary['Spacing']}**. Missing: ${spRows.filter((r) => !r.ok).map((r) => `${r.px}px×${r.count}`).join(', ') || 'none'}`)

  const tokRadii = (byCat.radii || []).map((v) => toPx(resolveVar(v.value))).filter((v) => v !== null)
  const rdRows = analysis.radii.map((r) => ({ ...r, px: toPx(r.value), ok: false })).map((r) => ({ ...r, ok: r.px === null ? true : tokRadii.some((t) => Math.abs(t - r.px) < 0.51 || (t >= 999 && r.px >= 999)) }))
  summary['Radii'] = `${pct(sum(rdRows.filter((r) => r.ok).map((r) => r.count)), sum(rdRows.map((r) => r.count)))}%`
  md.push(`\nRadii covered: **${summary['Radii']}**. Missing: ${rdRows.filter((r) => !r.ok).map((r) => `${r.value}×${r.count}`).join(', ') || 'none'}`)

  const parseShadow = (s) => String(s).split(/,(?![^(]*\))/).map((layer) => {
    const color = layer.match(/(rgba?\([^)]*\)|hsla?\([^)]*\)|#[0-9a-f]{3,8})/i)?.[0]
    const nums = [...layer.replace(color || '', '').matchAll(/-?[\d.]+/g)].map((m) => Number(m[0]))
    return { inset: /inset/.test(layer), nums: [nums[0] ?? 0, nums[1] ?? 0, nums[2] ?? 0, nums[3] ?? 0], color: color ? parseColor(color) : [0, 0, 0, 1] }
  })
  const sameShadow = (a, b) => {
    const A = parseShadow(a), B = parseShadow(b)
    return A.length === B.length && A.every((x, i) => x.inset === B[i].inset && x.nums.every((n, k) => Math.abs(n - B[i].nums[k]) < 0.6) && x.color && B[i].color && distance(flatten(x.color), flatten(B[i].color)) < 3)
  }
  const tokShadows = (byCat.shadows || []).map((v) => resolveVar(v.value))
  const shRows = analysis.shadows.map((s) => ({ ...s, ok: tokShadows.some((t) => sameShadow(s.value, t)) }))
  summary['Shadows'] = `${pct(sum(shRows.filter((r) => r.ok).map((r) => r.count)), sum(shRows.map((r) => r.count)))}%`
  md.push(`\nShadows covered: **${summary['Shadows']}**. Missing: ${shRows.filter((r) => !r.ok).map((r) => `\`${r.value.slice(0, 70)}\`×${r.count}`).join('; ') || 'none'}`)

  const tokBp = (byCat.breakpoints || []).map((v) => toPx(resolveVar(v.value))).filter(Boolean)
  const bpObs = analysis.breakpoints.minWidth.map((b) => b.px)
  const bpMiss = bpObs.filter((p) => !tokBp.some((t) => Math.abs(t - p) < 1))
  summary['Breakpoints'] = `${pct(bpObs.length - bpMiss.length, bpObs.length)}%`
  md.push(`\nBreakpoints (min-width queries): **${summary['Breakpoints']}**. Missing: ${bpMiss.join(', ') || 'none'}`)

  const toMs = (s) => (String(s).endsWith('ms') ? parseFloat(s) : parseFloat(s) * 1000)
  const tokDur = (byCat.durations || []).map((v) => toMs(resolveVar(v.value)))
  const dMiss = analysis.durations.filter((d) => !tokDur.some((t) => Math.abs(t - toMs(d.value)) < 1))
  md.push(`\nDurations missing: ${dMiss.map((d) => `${Math.round(toMs(d.value))}ms×${d.count}`).join(', ') || 'none'}`)
  const norm = (s) => String(s).replace(/\s+/g, '').replace(/\.0+(?=\D|$)/g, '').replace(/(^|[^\d])0\./g, '$1.')
  const tokEase = (byCat.easings || []).map((v) => norm(resolveVar(v.value)))
  const eMiss = analysis.easings.filter((e) => !tokEase.includes(norm(e.value)) && !['ease', 'linear', 'ease-in', 'ease-out', 'ease-in-out'].includes(e.value))
  md.push(`\nEasings missing: ${eMiss.map((e) => `${e.value}×${e.count}`).join(', ') || 'none'}`)
}

// ── report ──
const header = [`# Fidelity report`, ``, `Generated by \`verify.mjs\` on ${new Date().toISOString().slice(0, 10)} — do not hand-edit above the marker.`, ``,
  `**Build**: ${problems.length ? '⚠ ' + problems.join('; ') : '✓ compiles; every textStyle, layerStyle and recipe emits CSS'}`,
  `**Tokens**: ${Object.entries(byCat).map(([k, v]) => `${k} ${new Set(v.map((x) => x.token)).size}`).join(' · ')}`,
  `**Composition**: ${ts.length} textStyles · ${ls.length} layerStyles · ${Object.keys(recipes).length} recipes · dark values: ${values.filter((v) => v.condition).length}`]
if (analysis) header.push('', '| area | coverage |', '| --- | --- |', ...Object.entries(summary).map(([k, v]) => `| ${k} | ${v} |`))
if (buildNotes.length) header.push('', '**Compiler notes**', ...buildNotes.map((n) => `- ${n.trim()}`))
const MARK = '<!-- manual-notes -->'
const fpath = path.join(dir, 'FIDELITY.md')
const prior = fs.existsSync(fpath) ? fs.readFileSync(fpath, 'utf8') : ''
const keep = prior.includes(MARK) ? prior.slice(prior.indexOf(MARK)) : `${MARK}\n## Notes\n\n_Record deliberate deviations here: values observed but not tokenised, generated fill-in shades, fonts that need a licence._\n`
fs.writeFileSync(fpath, `${header.join('\n')}\n${md.join('\n')}\n\n---\n${keep}`)
fs.writeFileSync(path.join(s2p, 'coverage.json'), JSON.stringify({ problems, summary }, null, 2))

log(`\n${problems.length ? '✗' : '✓'} ${problems.length ? problems.join('\n  ') : 'preset compiles; all composition styles emit CSS'}`)
for (const [k, v] of Object.entries(summary)) log(`  ${k.padEnd(34)} ${v}`)
log(`  report → ${fpath}`)
process.exit(problems.length ? 1 : 0)
